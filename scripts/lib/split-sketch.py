#!/usr/bin/env python3
"""Split the React sketch components (upstream SketchEditor.tsx /
SketchPreview.tsx) into framework-free helper modules used by the Vue ports.

usage: split-sketch.py <components dir> [out dir]

<components dir> holds the (specifier-rewritten) upstream SketchEditor.tsx /
SketchPreview.tsx; [out dir] defaults to <components dir>/sketch.

Writes:
  sketch/editor-helpers.ts   — everything in SketchEditor.tsx except the
                               React component (types, constants, scene
                               conversion, DOM enhancements), all exported
  sketch/preview-model.ts    — SketchPreview.tsx's loading / caching / scene
                               conversion helpers (no JSX)
The Vue components (SketchEditor.vue, SketchPreview.vue) import them.
"""
import pathlib
import re
import sys

base = pathlib.Path(sys.argv[1])
out_dir = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else base / 'sketch'
out_dir.mkdir(parents=True, exist_ok=True)


def export_top_level(text: str) -> str:
    def repl(match: re.Match) -> str:
        return 'export ' + match.group(0)
    text = re.sub(r'^(?:async )?function \w+', repl, text, flags=re.M)
    text = re.sub(r'^const \w+', repl, text, flags=re.M)
    text = re.sub(r'^(?:interface|type) \w+', repl, text, flags=re.M)
    return text


# --- SketchEditor.tsx -------------------------------------------------------
editor = (base / 'SketchEditor.tsx').read_text()
head_end = editor.index('interface Props {')
types_start = editor.index('const SAVED_VISIBLE_MS')
types = editor[types_start:head_end]
body_start = editor.index('function buildInitialData(')
body = editor[body_start:]
# React-only helper
body = re.sub(r'function useLatestRef<T>\(value: T\): MutableRefObject<T> \{.*?\n\}\n\n', '', body, flags=re.S)
editor_out = (
    '// Framework-free parts of upstream apps/web/src/components/SketchEditor.tsx\n'
    '// (nexu-io/open-design, Apache-2.0): scene conversion, signatures, legacy\n'
    '// item conversion and the Excalidraw DOM enhancements (tooltips, i18n\n'
    '// overrides, context-menu simplification). Generated by\n'
    '// scripts/lib/split-sketch.py — the Vue SketchEditor.vue uses these.\n'
    "import { convertToExcalidrawElements, exportToBlob } from '@excalidraw/excalidraw';\n"
    "import type { AppState, BinaryFiles, ExcalidrawInitialDataState } from '@excalidraw/excalidraw/types';\n"
    "import type { OrderedExcalidrawElement } from '@excalidraw/excalidraw/element/types';\n"
    "import type { Locale } from '../../shims/i18n';\n"
    "import { readDefaultSketchToolColor } from '../sketch-colors';\n"
    "import { sanitizeExcalidrawAppState, type ExcalidrawSketchScene, type SketchItem } from '../sketch-model';\n\n"
    '// eslint-disable-next-line @typescript-eslint/no-unused-vars\n'
    'type _ExportToBlob = typeof exportToBlob;\n\n'
    + export_top_level(types)
    + export_top_level(body)
)
(out_dir / 'editor-helpers.ts').write_text(editor_out)

# --- SketchPreview.tsx ------------------------------------------------------
preview = (base / 'SketchPreview.tsx').read_text()
consts_start = preview.index('const DEFAULT_WIDTH')
consts_end = preview.index('export function computeSketchPreviewGeometry')
component_start = preview.index('export function SketchPreview(')
helpers_start = preview.index('async function buildSketchPreviewState(')
render_start = preview.index('function renderSketchSvgItem(')
preview_out = (
    '// Framework-free parts of upstream apps/web/src/components/SketchPreview.tsx\n'
    '// (nexu-io/open-design, Apache-2.0): preview state loading / caching and the\n'
    '// lightweight Excalidraw → SketchItem conversion. Generated by\n'
    '// scripts/lib/split-sketch.py — the Vue SketchPreview.vue uses these.\n'
    "import type { AppState, BinaryFiles } from '@excalidraw/excalidraw/types';\n"
    "import type { ExcalidrawElement, NonDeleted } from '@excalidraw/excalidraw/element/types';\n"
    "import type { ProjectFile } from '../../shims/types';\n"
    "import {\n  computeSketchBounds,\n  isSketchJsonFileName,\n  parseSketchWorkspaceDocument,\n  sketchSceneHasContent,\n"
    "  type ExcalidrawSketchScene,\n  type SketchItem,\n} from '../sketch-model';\n\n"
    + export_top_level(preview[consts_start:consts_end])
    + preview[consts_end:component_start]
    + export_top_level(preview[helpers_start:render_start])
)
(out_dir / 'preview-model.ts').write_text(preview_out)
print('wrote', out_dir / 'editor-helpers.ts', out_dir / 'preview-model.ts')
