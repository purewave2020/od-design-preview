import { chromium } from 'playwright-core';
const base = 'http://127.0.0.1:5178';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto(`${base}/?lang=en&theme=light&file=index.html`, { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.evaluate(() => { window.__m = []; window.addEventListener('message', (e) => { if (e.data && /od-edit/.test(e.data.type || '')) window.__m.push(e.data.type + (e.data.transform ? ':' + e.data.transform : '')); }); });
const viewer = page.locator('[data-testid="retained-file-viewer"]:not([aria-hidden])');
await viewer.getByTestId('manual-edit-mode-toggle').click();
await page.waitForTimeout(800);
const frame = await (await viewer.locator('[data-testid="artifact-preview-frame"]').elementHandle()).contentFrame();
const sel = process.argv[2] ?? 'h2';
await frame.locator(sel).first().scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
const b = await frame.locator(sel).first().boundingBox();
console.log('box', b);
await page.mouse.move(b.x + 20, b.y + b.height / 2);
await page.waitForTimeout(200);
await page.mouse.down();
for (let i = 1; i <= 10; i++) { await page.mouse.move(b.x + 20 + i * 6, b.y + b.height / 2 + i * 3); await page.waitForTimeout(16); }
await page.mouse.up();
await page.waitForTimeout(500);
console.log('transform', await frame.locator(sel).first().evaluate((el) => el.style.transform));
console.log('msgs', JSON.stringify(await page.evaluate(() => window.__m.filter((t) => !/targets|hover/.test(t)))));
await browser.close();
