import fs from 'node:fs';
import { chromium } from 'playwright-core';
const base = 'http://127.0.0.1:5178';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto(`${base}/?lang=en&theme=light&source=daemon&project=proj_demo`, { waitUntil: 'networkidle' });
await page.getByTestId('workspace-add-tab').click();
await page.getByTestId('tab-launcher-menu').locator('button', { hasText: 'New sketch' }).first().click();
const editor = page.getByTestId('sketch-excalidraw-editor');
await editor.waitFor({ timeout: 20000 });
await page.waitForTimeout(1500);
const tools = await editor.locator('[data-testid^="toolbar-"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-testid')));
console.log('tools', tools.join(','));
const rect = editor.locator('[data-testid="toolbar-rectangle"]');
console.log('rect tool count', await rect.count());
if (await rect.count()) await rect.first().click({ force: true });
const canvas = editor.locator('canvas').last();
const box = await canvas.boundingBox();
console.log('canvas', box);
await page.mouse.move(box.x + 300, box.y + 250);
await page.mouse.down();
await page.mouse.move(box.x + 520, box.y + 400, { steps: 8 });
await page.mouse.up();
await page.waitForTimeout(2500);
const name = await page.locator('.ws-tab.active').getAttribute('title');
const doc = JSON.parse(fs.readFileSync(`/tmp/odp-daemon-demo/${name}`, 'utf8'));
console.log(name, 'elements', doc.elements.length, doc.elements[0]?.type);
console.log('state', await page.getByTestId('sketch-save-state').textContent());
await editor.locator('[data-testid="main-menu-trigger"]').click();
await page.waitForTimeout(300);
const exp = page.getByTestId('sketch-menu-export-image');
console.log('export disabled?', await exp.isDisabled());
await exp.click();
await page.waitForTimeout(2500);
console.log('pngs', fs.readdirSync('/tmp/odp-daemon-demo').filter((f) => f.startsWith('sketch-') && f.endsWith('.png')));
console.log('toast', await page.locator('.od-toast').allTextContents().catch(() => []));
console.log('tabs', await page.locator('.ws-tab').evaluateAll((els) => els.map((e) => e.getAttribute('title'))));
await browser.close();
